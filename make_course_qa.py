GENERIC = {"b", "m", "tech", "msc", "sc", "bachelor", "master", "of", "in", "the", "and", "with", "for", "year",
           "integrated", "programme", "program", "curriculum", "specialization", "specialisation", "collaboration",
           "engineering", "science", "sciences", "computer", "cse", "technology"}


def key_tokens(name):
    toks = re.findall(r"[a-z0-9&]+", name.lower())
    return {t for t in toks if t not in GENERIC and not re.fullmatch(r"20\d\d|\d\d", t)}


def fmt(x):
    return str(int(x)) if float(x).is_integer() else str(x)


def credit_word(x):
    return "credit" if float(x) == 1 else "credits"


def make_rows(prog, r, unique_title, rng):
    code, title = r["code"], r["title"]
    c = fmt(r["credits"])
    ltp = f"{r['L']}-{r['T']}-{r['P']}-{c}" if r["J"] is None else f"{r['L']}-{r['T']}-{r['P']}-{r['J']}"
    rows = []

    q = rng.choice([
        f"How many credits does {code} ({title}) carry in the {prog} curriculum?",
        f"In the {prog} curriculum, what is the credit value of {code} {title}?",
        f"What credits are assigned to {code} {title} in the {prog} programme?",
    ])
    rows.append(("credits", q, f"{code} {title} carries {c} {credit_word(r['credits'])}."))

    if r["J"] is None:
        q = rng.choice([
            f"What is the L-T-P-C structure of {code} {title} in the {prog} curriculum?",
            f"In the {prog} curriculum, what are the L, T, P and C values of {code} ({title})?",
        ])
        a = f"{code} has an L-T-P-C of {ltp} ({c} {credit_word(r['credits'])})."
    else:
        q = rng.choice([
            f"What is the L-T-P-J structure and credit value of {code} {title} in the {prog} curriculum?",
            f"In the {prog} curriculum, what are the L-T-P-J hours and credits of {code} ({title})?",
        ])
        a = f"{code} has an L-T-P-J of {ltp} and carries {c} {credit_word(r['credits'])}."
    rows.append(("ltpc", q, a))

    q = rng.choice([
        f"What is the title of the course with code {code} in the {prog} curriculum?",
        f"In the {prog} curriculum, which course has the code {code}?",
    ])
    rows.append(("title", q, f"{code} is {title}."))

    if unique_title:
        q = rng.choice([
            f"What is the course code of {title} in the {prog} curriculum?",
            f"In the {prog} curriculum, what code is given to the course {title}?",
        ])
        rows.append(("code", q, f"The course code of {title} is {code}."))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tables", default="course_tables.jsonl")
    ap.add_argument("--out", default="extra_course_qa.jsonl")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--final-csv", default="final_qa_dataset.csv")
    ap.add_argument("--combined-csv", default="combined_qa_finetuning.csv")
    a = ap.parse_args()
    rng = random.Random(a.seed)

    tables = [json.loads(l) for l in open(a.tables, encoding="utf-8") if l.strip()]
    unknown = sorted({t["source"] for t in tables} - set(PROGRAMS))
    if unknown:
        print("no programme name for (skipped):", unknown)

    # (programme, code) -> numeric readings. The same course often appears twice in one PDF (once with a
    # J column, once without), so J is not part of the key; real conflicts are different credits or L-T-P.
    seen = defaultdict(lambda: defaultdict(lambda: {"titles": Counter(), "J": None}))
    for t in tables:
        prog = PROGRAMS.get(t["source"])
        if not prog:
            continue
        title = repair_text(t["title"])
        if len(title) > 90 or not re.search(r"[A-Za-z]{3}", title):
            continue
        slot = seen[(prog, t["code"])][(t["credits"], t["L"], t["T"], t["P"])]
        slot["titles"][title] += 1
        if t["J"] is not None:
            slot["J"] = t["J"]
    # L&T Civil is the base Civil curriculum plus changes: keep only what differs from the base
    def sig(v):
        return {(n, tuple(sorted(x["titles"]))) for n, x in v.items()}
    base = {k[1]: sig(v) for k, v in seen.items() if k[0] == "B.Tech Civil Engineering, 2024-2025"}
    for k in [k for k in seen if k[0].startswith("B.Tech Civil Engineering (L&T")]:
        if sig(seen[k]) == base.get(k[1]):
            del seen[k]

    # existing "this course is not in this programme" rows -> never contradict them
    qa = pd.concat([pd.read_csv(a.final_csv, encoding="utf-8-sig"), pd.read_csv(a.combined_csv, encoding="utf-8-sig")])
    forbidden = defaultdict(list)  # code -> token sets of the IDK question
    for q, ans in zip(qa["question"].astype(str), qa["answer"].astype(str)):
        if re.search(SOURCE_IDK_PATTERN, ans, re.I):
            q = repair_text(q)
            for code in COURSE_CODE.findall(q):
                forbidden[code].append(set(re.findall(r"[a-z0-9&]+", q.lower())))

    prog_titles = defaultdict(lambda: defaultdict(set))
    def best_title(slot):
        return sorted(slot["titles"].items(), key=lambda kv: (-kv[1], len(kv[0])))[0][0]

    for (prog, code), variants in seen.items():
        for slot in variants.values():
            prog_titles[prog][best_title(slot).lower()].add(code)

    out, stats = [], defaultdict(int)
    for (prog, code), variants in sorted(seen.items()):
        if len(variants) != 1:
            stats["ambiguous (conflicting readings)"] += 1
            continue
        pk = key_tokens(prog)
        if pk and any(pk <= qt for qt in forbidden.get(code, [])):
            stats["skipped: contradicts an existing IDK row"] += 1
            continue
        (credits, L, T, P), = variants.keys()
        slot = variants[(credits, L, T, P)]
        title, J = best_title(slot), slot["J"]
        row = {"code": code, "title": title, "credits": credits, "L": L, "T": T, "P": P, "J": J}
        unique = len(prog_titles[prog][title.lower()]) == 1
        for kind, q, ans in make_rows(prog, row, unique, rng):
            out.append({"question": q, "answer": ans, "is_idk": False, "source": "pdf_table",
                        "kind": kind, "program": prog})
        stats["courses used"] += 1

    # drop exact duplicate questions
    uniq, qs = [], set()
    for r in out:
        k = normalize(r["question"])
        if k not in qs:
            qs.add(k)
            uniq.append(r)
    write_jsonl(a.out, uniq)
    for k, v in sorted(stats.items()):
        print(f"{k}: {v}")
    kinds = defaultdict(int)
    for r in uniq:
        kinds[r["kind"]] += 1
    print(f"wrote {len(uniq)} rows to {a.out}  ({dict(kinds)}), {len({r['program'] for r in uniq})} programmes")


if __name__ == "__main__":
    main()
